// Input contains all data needed to generate a report.
type Input struct {
	Job            contracts.Job
	Target         contracts.Target
	Scope          contracts.Scope
	Plan           contracts.Plan
	Artifacts      []contracts.Artifact
	Evidence       []contracts.Evidence
	Findings       []contracts.Finding
	SkippedSteps   []string
	PluginFailures []PluginFailure
	Limitations    []string
	GeneratedTime  time.Time
}

// PluginFailure summarizes the latest non-successful state for one plugin step.
type PluginFailure struct {
	ToolCallID        string           `json:"tool_call_id"`
	StepID            string           `json:"step_id"`
	ToolName          string           `json:"tool_name"`
	Status            contracts.Status `json:"status"`
	ErrorClass        string           `json:"error_class,omitempty"`
	Reason            string           `json:"reason,omitempty"`
	PolicyDecision    string           `json:"policy_decision,omitempty"`
	ApprovalRequestID string           `json:"approval_request_id,omitempty"`
	Runtime           string           `json:"runtime,omitempty"`
	Risk              string           `json:"risk,omitempty"`
}

// Output describes generated report files.
type Output struct {
	Report   contracts.Report
	MDPath   string
	JSONPath string
}

// Generate writes Markdown and JSON reports to workspace/reports.
func Generate(workspace string, input Input) (Output, error) {
	if input.GeneratedTime.IsZero() {
		input.GeneratedTime = contracts.Now()
	}
	reportDir := filepath.Join(workspace, "reports")
	if err := os.MkdirAll(reportDir, 0o755); err != nil {
		return Output{}, fmt.Errorf("create report dir: %w", err)
	}

	r := redactor.New()
	md := r.Redact(renderMarkdown(input))
	mdPath := filepath.Join(reportDir, "report.md")
	if err := os.WriteFile(mdPath, []byte(md), 0o644); err != nil {
		return Output{}, fmt.Errorf("write report.md: %w", err)
	}

	jsonPath := filepath.Join(reportDir, "report.json")
	reportData := struct {
		Job            contracts.Job        `json:"job"`
		Target         contracts.Target     `json:"target"`
		Scope          contracts.Scope      `json:"scope"`
		Plan           contracts.Plan       `json:"plan"`
		Evidence       []contracts.Evidence `json:"evidence"`
		Findings       []contracts.Finding  `json:"findings"`
		Artifacts      []contracts.Artifact `json:"artifacts"`
		PluginFailures []PluginFailure      `json:"plugin_failures,omitempty"`
	}{input.Job, input.Target, input.Scope, input.Plan, input.Evidence, input.Findings, input.Artifacts, input.PluginFailures}
	encoded, err := json.MarshalIndent(reportData, "", "  ")
	if err != nil {
		return Output{}, fmt.Errorf("marshal report.json: %w", err)
	}
	if err := os.WriteFile(jsonPath, encoded, 0o644); err != nil {
		return Output{}, fmt.Errorf("write report.json: %w", err)
	}

	findingIDs := make([]string, 0, len(input.Findings))
	for _, finding := range input.Findings {
		findingIDs = append(findingIDs, finding.ID)
	}
	report := contracts.Report{
		ID:          "report_001",
		JobID:       input.Job.ID,
		Formats:     []string{"markdown", "json"},
		Paths:       map[string]string{"markdown": "reports/report.md", "json": "reports/report.json"},
		FindingIDs:  findingIDs,
		GeneratedAt: input.GeneratedTime,
		Generator:   "builtin.reporter.markdown.v1",
	}
	return Output{Report: report, MDPath: mdPath, JSONPath: jsonPath}, nil
}

func renderMarkdown(input Input) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# CyberAgent Report\n\n")
	fmt.Fprintf(&b, "## 1. Summary\n\n")
	fmt.Fprintf(&b, "- Target: `%s`\n", input.Target.Value)
	fmt.Fprintf(&b, "- Scope ID: `%s`\n", input.Scope.ID)
	fmt.Fprintf(&b, "- Profile: `%s`\n", input.Job.Profile)
	fmt.Fprintf(&b, "- Job: `%s`\n", input.Job.ID)
	fmt.Fprintf(&b, "- Status: `%s`\n", input.Job.Status)
	fmt.Fprintf(&b, "- Findings: `%d`\n\n", len(input.Findings))

	fmt.Fprintf(&b, "## 2. Execution Overview\n\n")
	fmt.Fprintf(&b, "- Planner: `%s`\n", input.Plan.Planner)
	fmt.Fprintf(&b, "- Steps planned: `%d`\n", len(input.Plan.Steps))
	if len(input.SkippedSteps) > 0 {
		fmt.Fprintf(&b, "- Steps skipped: `%s`\n", strings.Join(input.SkippedSteps, ", "))
	}
	fmt.Fprintf(&b, "- Evidence items: `%d`\n", len(input.Evidence))
	fmt.Fprintf(&b, "- Artifacts: `%d`\n\n", len(input.Artifacts))

	fmt.Fprintf(&b, "## 3. Findings\n\n")
	if len(input.Findings) == 0 {
		fmt.Fprintf(&b, "No findings were generated by the enabled checks.\n\n")
	} else {
		for _, finding := range input.Findings {
			fmt.Fprintf(&b, "### %s\n\n", finding.Title)
			fmt.Fprintf(&b, "- Severity: `%s`\n", finding.Severity)
			fmt.Fprintf(&b, "- Confidence: `%s`\n", finding.Confidence)
			fmt.Fprintf(&b, "- Category: `%s`\n", finding.Category)
			fmt.Fprintf(&b, "- Affected: `%s`\n", strings.Join(finding.AffectedTargets, ", "))
			fmt.Fprintf(&b, "- Evidence: `%s`\n\n", strings.Join(finding.EvidenceIDs, ", "))
			fmt.Fprintf(&b, "%s\n\n", finding.Description)
			if finding.Impact != "" {
				fmt.Fprintf(&b, "Impact: %s\n\n", finding.Impact)
			}
			if len(finding.Reproduction) > 0 {
				fmt.Fprintf(&b, "Reproduction:\n")
				for _, step := range finding.Reproduction {
					fmt.Fprintf(&b, "- `%s`\n", step)
				}
				fmt.Fprintf(&b, "\n")
			}
			if finding.Remediation != "" {
				fmt.Fprintf(&b, "Remediation: %s\n\n", finding.Remediation)
			}
		}
	}

	fmt.Fprintf(&b, "## 4. Evidence Index\n\n")
	for _, evidence := range input.Evidence {
		fmt.Fprintf(&b, "- `%s` [%s] %s", evidence.ID, evidence.Type, evidence.Title)
		if evidence.ArtifactID != "" {
			fmt.Fprintf(&b, " (artifact: `%s`)", evidence.ArtifactID)
		}
		fmt.Fprintf(&b, "\n")
	}
	fmt.Fprintf(&b, "\n## 5. Artifacts\n\n")
	for _, artifact := range input.Artifacts {
		fmt.Fprintf(&b, "- `%s` → `%s` (%s, %d bytes)\n", artifact.ID, artifact.Path, artifact.Type, artifact.SizeBytes)
	}

	if len(input.PluginFailures) > 0 {
		fmt.Fprintf(&b, "\n## 6. Plugin Execution Notes\n\n")
		for _, failure := range input.PluginFailures {
			fmt.Fprintf(&b, "- `%s` step `%s` status `%s`", failure.ToolName, failure.StepID, failure.Status)
			if failure.ErrorClass != "" {
				fmt.Fprintf(&b, " class `%s`", failure.ErrorClass)
			}
			if failure.Reason != "" {
				fmt.Fprintf(&b, ": %s", failure.Reason)
			}
			fmt.Fprintf(&b, "\n")
			if failure.PolicyDecision != "" || failure.ApprovalRequestID != "" {
				fmt.Fprintf(&b, "  - policy: `%s`; approval: `%s`\n", emptyReportField(failure.PolicyDecision), emptyReportField(failure.ApprovalRequestID))
			}
		}
	}

	limitationsSection := 6
	if len(input.PluginFailures) > 0 {
		limitationsSection = 7
	}
	fmt.Fprintf(&b, "\n## %d. Limitations\n\n", limitationsSection)
	limitations := input.Limitations
	if len(limitations) == 0 {
		limitations = []string{"Only low-risk built-in checks were executed unless optional plugins were explicitly enabled."}
	}
	for _, limitation := range limitations {
		fmt.Fprintf(&b, "- %s\n", limitation)
	}
	return b.String()
}

// BuildEvidenceIndex creates a findings.EvidenceIndex from slices.
func BuildEvidenceIndex(artifacts []contracts.Artifact, evidence []contracts.Evidence) findings.EvidenceIndex {
	return findings.EvidenceIndex{Artifacts: artifacts, Evidence: evidence}
}

// PluginFailuresFromToolCalls returns the latest non-successful plugin call per plugin step.
func PluginFailuresFromToolCalls(calls []contracts.ToolCall) []PluginFailure {
	type latestCall struct {
		call  contracts.ToolCall
		index int
	}
	latest := map[string]latestCall{}
	for i, call := range calls {
		if call.Kind != contracts.ToolCallKindPlugin && !strings.HasPrefix(call.ToolName, "plugin.") {
			continue
		}
		key := call.StepID + "\x00" + call.ToolName
		latest[key] = latestCall{call: call, index: i}
	}

	ordered := make([]latestCall, 0, len(latest))
	for _, item := range latest {
		if item.call.Status == contracts.StatusSucceeded {
			continue
		}
		ordered = append(ordered, item)
	}
	sort.SliceStable(ordered, func(i, j int) bool { return ordered[i].index < ordered[j].index })

	failures := make([]PluginFailure, 0, len(ordered))
	for _, item := range ordered {
		call := item.call
		failures = append(failures, PluginFailure{
			ToolCallID:        call.ID,
			StepID:            call.StepID,
			ToolName:          call.ToolName,
			Status:            call.Status,
			ErrorClass:        metadataString(call.Metadata, "error_class"),
			Reason:            call.Error,
			PolicyDecision:    metadataString(call.Metadata, "policy_decision"),
			ApprovalRequestID: metadataString(call.Metadata, "approval_request_id"),
			Runtime:           metadataString(call.Metadata, "runtime"),
			Risk:              metadataString(call.Metadata, "risk"),
		})
	}
	return failures
}

func metadataString(metadata contracts.Metadata, key string) string {
	if metadata == nil {
		return ""
	}
	if value, ok := metadata[key]; ok && value != nil {
		return fmt.Sprintf("%v", value)
	}
	return ""
}

func emptyReportField(value string) string {
	if strings.TrimSpace(value) == "" {
		return "-"
	}
	return value
}
